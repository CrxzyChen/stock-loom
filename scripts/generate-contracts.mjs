import fs from 'node:fs';
import {createHash} from 'node:crypto';
const schema=JSON.parse(fs.readFileSync('packages/contracts/schema.json','utf8'));
// Canonical key order makes whitespace and object-key ordering irrelevant.
function canonical(value){return Array.isArray(value)?value.map(canonical):value!==null&&typeof value==='object'?Object.fromEntries(Object.keys(value).sort().map(k=>[k,canonical(value[k])])):value}
const fingerprint=createHash('sha256').update(JSON.stringify(canonical(schema))).digest('hex');
const defs=schema.$defs;
const responses=schema['x-rpc-responses']??{};
const requests=schema['x-rpc-requests']??{};
for(const [method,name] of Object.entries(requests))if(!/^[a-z]+(?:\.[a-zA-Z]+)*$/.test(method)||!defs[name])throw Error('Invalid RPC request mapping');
for(const [method,name] of Object.entries(responses))if(!/^[a-z]+(?:\.[a-zA-Z]+)*$/.test(method)||!defs[name])throw Error('Invalid RPC response mapping');
function check(s){
  const keys=s.$ref?['$ref']:'const' in s?['const']:s.enum?['enum']:s.anyOf?['anyOf']:s.type==='object'?['type','properties','required','additionalProperties']:s.type==='array'?['type','items','maxItems','minItems']:['type','minimum','maximum'];
  if(Object.keys(s).some(k=>!keys.includes(k)))throw Error('Unsupported schema keyword');
  if(s.anyOf)s.anyOf.forEach(check);
  if(s.properties)Object.values(s.properties).forEach(check);
  if(s.items)check(s.items);
}
Object.values(defs).forEach(check);
function type(s,python=false){
  if(s.$ref){const name=s.$ref.replace('#/$defs/','');if(!defs[name])throw Error('Unknown reference '+s.$ref);return name}
  if(s.const!==undefined)return python?`Literal[${(s.const===false?'False':s.const===true?'True':JSON.stringify(s.const))}]`:JSON.stringify(s.const);
  if(s.enum)return python?`Literal[${s.enum.map(x=>JSON.stringify(x)).join(', ')}]`:s.enum.map(x=>JSON.stringify(x)).join(' | ');
  if(s.anyOf)return s.anyOf.map(x=>type(x,python)).join(' | ');
  if(s.type==='array')return python?`list[${type(s.items,true)}]`:`Array<${type(s.items)}>`;
  const primitive=python?{string:'str',integer:'int',number:'float',boolean:'bool',null:'None'}:{string:'string',integer:'number',number:'number',boolean:'boolean',null:'null'};
  if(primitive[s.type])return primitive[s.type];
  throw Error('Unsupported schema type '+JSON.stringify(s));
}
let ts='// Generated by scripts/generate-contracts.mjs. Edit schema.json.\n';
let py='# Generated by scripts/generate-contracts.mjs. Edit schema.json.\nfrom __future__ import annotations\nfrom typing import TypedDict, Literal, NotRequired\n\n';
for(const [name,s] of Object.entries(defs)){
  if(!/^[A-Z][A-Za-z0-9]*$/.test(name))throw Error('Invalid type name');
  if(s.type!=='object'){ts+=`export type ${name} = ${type(s)};\n`;py+=`${name} = ${type(s,true)}\n\n`;continue}
  if(s.additionalProperties!==false)throw Error('Explicit closed objects required');
  const required=new Set(s.required??[]);for(const key of required)if(!s.properties[key])throw Error('Unknown required property');
  ts+=`export interface ${name} {\n`;py+=`class ${name}(TypedDict):\n`;
  for(const [key,value] of Object.entries(s.properties)){
    if(!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(key))throw Error('Invalid property');
    ts+=`  ${key}${required.has(key)?'':'?'}: ${type(value)};\n`;
    const t=type(value,true);py+=`    ${key}: ${required.has(key)?t:`NotRequired[${t}]`}\n`;
  }
  if(!Object.keys(s.properties).length)py+='    pass\n';
  ts+='}\n';py+='\n';
}
const json=JSON.stringify(defs);
const runtime=`// Generated from schema.json.\nimport {matchesSchema} from './validate.mjs';\nconst definitions=${json};\nexport const matchesContract=(name,value)=>Object.hasOwn(definitions,name)&&matchesSchema(definitions[name],value,definitions);\nconst responses=${JSON.stringify(responses)};\nexport const matchesRpcResponse=(method,value)=>!Object.hasOwn(responses,method)||matchesContract(responses[method],value);\n`;
py+=`import json as _json\nfrom contract_validation import matches_schema as _matches_schema\n_DEFINITIONS = _json.loads(${JSON.stringify(json)})\ndef matches_contract(name, value):\n    return name in _DEFINITIONS and _matches_schema(_DEFINITIONS[name],value,_DEFINITIONS)\n`;
py+=`_RESPONSES = _json.loads(${JSON.stringify(JSON.stringify(responses))})\ndef matches_rpc_response(method,value):\n    return method not in _RESPONSES or matches_contract(_RESPONSES[method],value)\n`;
const requestRuntime=`export const CONTRACT_FINGERPRINT=${JSON.stringify(fingerprint)};\nconst requests=${JSON.stringify(requests)};\nexport const matchesRpcRequest=(method,value)=>!Object.hasOwn(requests,method)||matchesContract(requests[method],value);\n`;
py+=`_REQUESTS = _json.loads(${JSON.stringify(JSON.stringify(requests))})\ndef matches_rpc_request(method,value):\n    return method not in _REQUESTS or matches_contract(_REQUESTS[method],value)\n`;
py+=`CONTRACT_FINGERPRINT = ${JSON.stringify(fingerprint)}\n`;
for(const [file,content] of [['packages/contracts/generated.ts',ts],['packages/contracts/generated-runtime.mjs',runtime+requestRuntime],['apps/data-service/generated_contracts.py',py]]){
  if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error('Generated contract drift: '+file)}else fs.writeFileSync(file,content);
}
console.log(`Contracts ${process.argv.includes('--check')?'checked':'generated'}: ${Object.keys(defs).length} shared types`);
