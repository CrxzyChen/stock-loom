import fs from 'node:fs';
import path from 'node:path';
import {randomUUID,createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {extractFile} from '@electron/asar';
const build=JSON.parse(fs.readFileSync('build/package-current.json','utf8'));
const root=path.join(build.directory,'win-unpacked'),archive=path.join(root,'resources/app.asar');
const pkg=JSON.parse(extractFile(archive,'package.json').toString());
if(pkg.version!==JSON.parse(fs.readFileSync('package.json','utf8')).version)throw Error('Build a matching application version first');
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const before={archive:hash(archive),executable:hash(path.join(root,'Stock Loom.exe'))};
const output=path.resolve('release/upgrade-tests',randomUUID());fs.mkdirSync(output,{recursive:true});
const config=JSON.parse(fs.readFileSync(path.join(build.directory,'builder-config.json'),'utf8'));
config.appId='com.crxzy.stock.round4-upgrade-test';
config.directories.output=output;
config.artifactName='Stock-Loom-Upgrade-Test-${version}-${arch}.${ext}';
config.nsis={...config.nsis,guid:'56fbb838-6471-4ead-b330-420458447a37',uninstallDisplayName:'Stock Loom Round 4 Upgrade Test',createDesktopShortcut:false,createStartMenuShortcut:false,runAfterFinish:false,include:path.resolve('scripts/installer-running-check.nsh')};
const file=path.join(output,'builder-config.json');fs.writeFileSync(file,JSON.stringify(config,null,2));
const done=spawnSync(process.execPath,[path.resolve('node_modules/electron-builder/cli.js'),'--config',file,'--win','--x64','--prepackaged',root],{stdio:'inherit',windowsHide:true});
if(done.status!==0)process.exit(done.status??1);
if(hash(archive)!==before.archive||hash(path.join(root,'Stock Loom.exe'))!==before.executable)throw Error('Prepackaged application changed');
const installer=path.join(output,`Stock-Loom-Upgrade-Test-${pkg.version}-x64.exe`);
const record={version:pkg.version,sourceBuild:build.directory,directory:output,installer,sha256:hash(installer),payload:before,guid:config.nsis.guid,appId:config.appId,shortcuts:false,releaseArtifact:false};
fs.writeFileSync(path.join(output,'identity.json'),JSON.stringify(record,null,2));fs.writeFileSync('validation/round4-upgrade-test-package.json',JSON.stringify(record,null,2));console.log(JSON.stringify(record));
