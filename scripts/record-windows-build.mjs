import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {inspectSignature} from '../apps/desktop/src/main/installer-signature.mjs';
import {validateMcpEvidence} from '../apps/agent-host/mcp-config.mjs';
import {disabledFeatures} from '../apps/agent-host/runtime.mjs';
import {CONTRACT_FINGERPRINT} from '../packages/contracts/generated-runtime.mjs';
import {verifyDesktopArchive} from './desktop-build-manifest.mjs';
import {verifyPackagedNotices} from './verify-packaged-notices.mjs';

const build=JSON.parse(fs.readFileSync('build/package-current.json','utf8'));
const version=JSON.parse(fs.readFileSync('package.json','utf8')).version;
const installer=path.join(build.directory,`Stock-Loom-${version}-x64.exe`);
const unpacked=path.join(build.directory,'win-unpacked');
const evidence=JSON.parse(fs.readFileSync(path.join(unpacked,'resources/codex-mcp-electron-probe.json'),'utf8'));
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
validateMcpEvidence(evidence,disabledFeatures);
for(const [field,file] of [['commandSha256','Stock Loom.exe'],['bridgeSha256','resources/tools/mcp-server.mjs'],['binarySha256','resources/codex/codex.exe']])assert.equal(hash(path.join(unpacked,file)),evidence[field]);
assert.equal(hash(path.join(unpacked,'resources/service/stock-data.exe')),build.service.binarySha256);
const signature=await inspectSignature(installer);
const archive=path.join(unpacked,'resources/app.asar');
if(!build.desktop)throw Error('Package has no desktop build manifest; rebuild before recording.');
verifyDesktopArchive(archive,build.desktop);
const bundledFiles=build.desktop.files;
const record={createdAt:new Date().toISOString(),path:installer,bytes:fs.statSync(installer).size,sha256:hash(installer),signatureStatus:signature.status,serviceSha256:build.service.binarySha256,runtime:build.service.runtime,packagedMcpVerified:true,installerExecuted:false,releaseStatus:'development-validation-only'};
const handshake=JSON.parse(fs.readFileSync(path.join(build.directory,'service-handshake.json'),'utf8'));
assert.equal(handshake.passed,true);assert.equal(handshake.sha256,record.serviceSha256);assert.equal(handshake.contractFingerprint,CONTRACT_FINGERPRINT);
record.serviceHandshake=handshake;
record.appAsarSha256=hash(archive);record.bundledFiles=bundledFiles;
record.notices=verifyPackagedNotices(path.join(unpacked,'resources'));
fs.writeFileSync(path.join(build.directory,'build-record.json'),JSON.stringify(record,null,2));
fs.writeFileSync('validation/windows-build-latest.json',JSON.stringify(record,null,2));
console.log(JSON.stringify(record));
